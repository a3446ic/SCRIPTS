SELECT C.RAMO,C.ACTIVO,C.NUM_POLIZA,C.NUM_ANUALIDAD,C.P_INTERMEDIACION,C.COD_MEDIADOR||'-'||C.COD_SUBCLAVE MEDIADOR
, LPAD(C.IDMODALIDAD,3,0) MODALIDAD_CARTERA
, CASE 
	WHEN R.NUM_POLIZA IS NULL THEN 'NO'
	ELSE 'SI'
END EN_RELASUJE
,R.POSITIONNAME,LPAD(R.MOD,3,0) MODALIDAD_RELASUJE
, CASE
	WHEN  R.NUM_POLIZA IS NULL THEN '-'
	ELSE CASE
			WHEN C.COD_MEDIADOR||'-'||C.COD_SUBCLAVE = R.POSITIONNAME THEN 'SI'
			ELSE 'NO'
		END
END MISMO_MEDIADOR
, CASE	
	WHEN  R.NUM_POLIZA IS NULL THEN 'PÓLIZA NO EXISTE EN RELASUJE'
	ELSE CASE
			WHEN R.POSITIONNAME IS NULL THEN 'MEDIADOR NULL EN RELASUJE'
			WHEN C.COD_MEDIADOR||'-'||C.COD_SUBCLAVE = R.POSITIONNAME THEN 'COINCIDE MEDIADOR'
			WHEN C.COD_MEDIADOR = SUBSTRING(R.POSITIONNAME,1,4) AND C.COD_SUBCLAVE != SUBSTRING(R.POSITIONNAME,5,9) THEN 'DISTINTA SUBCLAVE'
			WHEN (SELECT COUNT(*) FROM EXT.RELASUJE RJ WHERE RJ.NUM_POLIZA = C.NUM_POLIZA AND LPAD(C.IDMODALIDAD,3,0) = LPAD(RJ.MOD,3,0)) > 1 THEN 'VARIOS MEDIADORES EN RELASUJE'
			ELSE 'DISTINTO MEDIADOR'
		END
END TIPO_CASO
FROM EXT.CARTERA C
LEFT JOIN EXT.RELASUJE R ON C.NUM_POLIZA = R.NUM_POLIZA AND LPAD(C.IDMODALIDAD,3,0) = LPAD(R.MOD,3,0)
LEFT JOIN (SELECT *
						,ROW_NUMBER() OVER (PARTITION BY CR.NUM_POLIZA ORDER BY CR.NUM_ANUALIDAD DESC) AS RN
					FROM EXT.CARTERA CR 
					WHERE  ACTIVO > 0
					AND RAMO = 'CREDITO'
					--AND CR.NUM_POLIZA = V_NUM_POLIZA
					) CRT ON C.NUM_POLIZA = CRT.NUM_POLIZA AND CRT.COD_MEDIADOR = C.COD_MEDIADOR AND CRT.COD_SUBCLAVE = C.COD_SUBCLAVE  AND CRT.NUM_ANUALIDAD = C.NUM_ANUALIDAD
WHERE C.ACTIVO > 0
AND C. RAMO = 'CREDITO'
AND CRT.RN = 1
UNION ALL
SELECT C.RAMO,C.ACTIVO,C.NUM_POLIZA,C.NUM_ANUALIDAD,C.P_INTERMEDIACION,C.COD_MEDIADOR||'-'||C.COD_SUBCLAVE MEDIADOR
, LPAD(C.IDMODALIDAD,3,0) MODALIDAD_CARTERA
, CASE 
	WHEN R.NUM_POLIZA IS NULL THEN 'NO'
	ELSE 'SI'
END EN_RELASUJE
,R.POSITIONNAME,LPAD(R.MOD,3,0) MODALIDAD_RELASUJE
, CASE
	WHEN  R.NUM_POLIZA IS NULL THEN '-'
	ELSE CASE
			WHEN C.COD_MEDIADOR||'-'||C.COD_SUBCLAVE = R.POSITIONNAME THEN 'SI'
			ELSE 'NO'
		END
END MISMO_MEDIADOR
, CASE	
	WHEN  R.NUM_POLIZA IS NULL THEN 'PÓLIZA NO EXISTE EN RELASUJE'
	ELSE CASE
			WHEN R.POSITIONNAME IS NULL THEN 'MEDIADOR NULL EN RELASUJE'
			WHEN C.COD_MEDIADOR||'-'||C.COD_SUBCLAVE = R.POSITIONNAME THEN 'COINCIDE MEDIADOR'
			WHEN C.COD_MEDIADOR = SUBSTRING(R.POSITIONNAME,1,4) AND C.COD_SUBCLAVE != SUBSTRING(R.POSITIONNAME,5,9) THEN 'DISTINTA SUBCLAVE'
			WHEN (SELECT COUNT(*) FROM EXT.RELASUJE RJ WHERE RJ.NUM_POLIZA = C.NUM_POLIZA AND LPAD(C.IDMODALIDAD,3,0) = LPAD(RJ.MOD,3,0)) > 1 THEN 'VARIOS MEDIADORES EN RELASUJE'
			ELSE 'DISTINTO MEDIADOR'
		END
END TIPO_CASO
FROM EXT.CARTERA C
LEFT JOIN EXT.RELASUJE R ON C.NUM_POLIZA = R.NUM_POLIZA AND LPAD(C.IDMODALIDAD,3,0) = LPAD(R.MOD,3,0) AND LPAD(R.MOD,3,0) IN ('091','098')
WHERE C.RAMO = 'CAUCION'
AND C.NUM_FIANZA IS NULL
ORDER BY C.NUM_POLIZA