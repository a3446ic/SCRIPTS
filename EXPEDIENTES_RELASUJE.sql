	AND NOT EXISTS (SELECT 1 FROM EXT.CARTERA C WHERE C.RAMO = 'CAUCION' AND C.NUM_FIANZA IS NULL AND C.MODIF_USER NOT LIKE '%EXPEDIENTE%' AND C.NUM_POLIZA = R.NUM_POLIZA)
